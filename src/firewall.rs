//! The nftables ruleset that limits where session users can connect.
//!
//! Every session runs as its own Unix user. Packets from those users are
//! matched by uid in the output hook; packets from anyone else (root, you,
//! tailscaled) are left alone. A session may send only:
//!   - to loopback,
//!   - DNS to the configured nameservers,
//!   - HTTPS anywhere (if enabled; Claude Code needs Anthropic),
//!   - to the address and SSH port of each host granted to it and not blocked.
//!
//! Everything else is rejected.
//!
//! There is deliberately no "established connections are fine" rule: when a
//! host is blocked or revoked, packets on connections already open to it are
//! rejected too, so the cut is immediate.

use anyhow::{bail, Context, Result};
use std::fmt::Write as _;
use std::io::Write as _;
use std::net::IpAddr;
use std::process::{Command, Stdio};

pub const TABLE: &str = "blackthorn";

#[derive(Debug, Clone)]
pub struct SessionRules {
    pub name: String,
    pub uid: u32,
    pub allow: Vec<(String, IpAddr, u16)>,
}

#[derive(Debug, Clone)]
pub struct Plan {
    pub sessions: Vec<SessionRules>,
    pub dns: Vec<IpAddr>,
    pub https_anywhere: bool,
}

fn addr_match(a: &IpAddr) -> String {
    match a {
        IpAddr::V4(v4) => format!("ip daddr {v4}"),
        IpAddr::V6(v6) => format!("ip6 daddr {v6}"),
    }
}

fn set<T: std::fmt::Display>(items: impl IntoIterator<Item = T>) -> String {
    let parts: Vec<String> = items.into_iter().map(|i| i.to_string()).collect();
    format!("{{ {} }}", parts.join(", "))
}

pub fn render(plan: &Plan) -> String {
    let mut out = String::new();
    out.push_str("# Generated by thorn. Replaced as a whole by `thorn firewall apply`.\n");
    // Declaring then deleting the table makes the load idempotent: the file
    // works whether or not the table exists, and the swap is atomic.
    let _ = writeln!(out, "table inet {TABLE}");
    let _ = writeln!(out, "delete table inet {TABLE}");
    let _ = writeln!(out, "table inet {TABLE} {{");
    out.push_str("\tchain output {\n");
    out.push_str("\t\ttype filter hook output priority filter; policy accept;\n");

    if !plan.sessions.is_empty() {
        let uids = set(plan.sessions.iter().map(|s| s.uid));
        let _ = writeln!(out, "\t\t# Only session users are restricted.");
        let _ = writeln!(out, "\t\tmeta skuid != {uids} accept");
        out.push_str("\t\toifname \"lo\" accept\n");

        let dns4: Vec<_> = plan.dns.iter().filter(|a| a.is_ipv4()).collect();
        let dns6: Vec<_> = plan.dns.iter().filter(|a| a.is_ipv6()).collect();
        if !dns4.is_empty() {
            let _ = writeln!(
                out,
                "\t\tip daddr {} meta l4proto {{ tcp, udp }} th dport 53 accept",
                set(dns4)
            );
        }
        if !dns6.is_empty() {
            let _ = writeln!(
                out,
                "\t\tip6 daddr {} meta l4proto {{ tcp, udp }} th dport 53 accept",
                set(dns6)
            );
        }
        if plan.https_anywhere {
            out.push_str("\t\ttcp dport 443 accept\n");
        }
        for s in &plan.sessions {
            let _ = writeln!(out, "\t\t# session {}", s.name);
            for (host, addr, port) in &s.allow {
                let _ = writeln!(
                    out,
                    "\t\tmeta skuid {} {} tcp dport {} accept comment \"{}\"",
                    s.uid,
                    addr_match(addr),
                    port,
                    host
                );
            }
        }
        out.push_str("\t\tmeta l4proto tcp counter reject with tcp reset\n");
        out.push_str("\t\tcounter reject with icmpx type admin-prohibited\n");
    }
    out.push_str("\t}\n}\n");
    out
}

pub fn apply(ruleset: &str) -> Result<()> {
    nft_stdin(&["-f", "-"], ruleset).context("applying the blackthorn firewall")
}

pub fn check(ruleset: &str) -> Result<()> {
    nft_stdin(&["-c", "-f", "-"], ruleset).context("checking the blackthorn firewall")
}

fn nft_stdin(args: &[&str], input: &str) -> Result<()> {
    let mut child = Command::new("nft")
        .args(args)
        .stdin(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("running nft (is the nftables package installed?)")?;
    child
        .stdin
        .take()
        .expect("piped stdin")
        .write_all(input.as_bytes())?;
    let out = child.wait_with_output()?;
    if !out.status.success() {
        bail!(
            "nft failed: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(())
}

/// The table as currently loaded in the kernel.
pub fn show() -> Result<String> {
    let out = Command::new("nft")
        .args(["list", "table", "inet", TABLE])
        .output()
        .context("running nft")?;
    if !out.status.success() {
        bail!(
            "the blackthorn table is not loaded: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn plan() -> Plan {
        Plan {
            sessions: vec![
                SessionRules {
                    name: "ops".into(),
                    uid: 990,
                    allow: vec![
                        ("fig".into(), "100.80.0.3".parse().unwrap(), 22),
                        ("nas".into(), "fd7a:115c:a1e0::5".parse().unwrap(), 2222),
                    ],
                },
                SessionRules {
                    name: "idle".into(),
                    uid: 991,
                    allow: vec![],
                },
            ],
            dns: vec![
                "100.100.100.100".parse().unwrap(),
                "fd7a::53".parse().unwrap(),
            ],
            https_anywhere: true,
        }
    }

    #[test]
    fn restricts_only_session_uids() {
        let r = render(&plan());
        assert!(r.contains("meta skuid != { 990, 991 } accept"));
    }

    #[test]
    fn grants_are_per_uid_address_and_port() {
        let r = render(&plan());
        assert!(r.contains("meta skuid 990 ip daddr 100.80.0.3 tcp dport 22 accept"));
        assert!(r.contains("meta skuid 990 ip6 daddr fd7a:115c:a1e0::5 tcp dport 2222 accept"));
        assert!(!r.contains("meta skuid 991 ip"));
    }

    #[test]
    fn no_established_shortcut_and_ends_in_reject() {
        let r = render(&plan());
        assert!(!r.contains("established"));
        let last_rule = r
            .lines()
            .rev()
            .find(|l| l.trim_start().starts_with("counter"))
            .unwrap();
        assert!(last_rule.contains("reject"));
    }

    #[test]
    fn dns_and_https() {
        let r = render(&plan());
        assert!(
            r.contains("ip daddr { 100.100.100.100 } meta l4proto { tcp, udp } th dport 53 accept")
        );
        assert!(r.contains("ip6 daddr { fd7a::53 } meta l4proto { tcp, udp } th dport 53 accept"));
        assert!(r.contains("tcp dport 443 accept"));
        let mut p = plan();
        p.https_anywhere = false;
        assert!(!render(&p).contains("dport 443"));
    }

    /// Needs root and nft: `sudo cargo test -- --ignored`. Checks only
    /// (nft -c); nothing is loaded.
    #[test]
    #[ignore]
    fn nft_accepts_the_ruleset() {
        check(&render(&plan())).unwrap();
        check(&render(&Plan {
            sessions: vec![],
            dns: vec![],
            https_anywhere: true,
        }))
        .unwrap();
    }

    #[test]
    fn empty_plan_restricts_nobody() {
        let r = render(&Plan {
            sessions: vec![],
            dns: vec![],
            https_anywhere: true,
        });
        assert!(!r.contains("skuid"));
        assert!(!r.contains("reject"));
        assert!(r.contains("policy accept"));
    }
}
